    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        int linha = tblLivros.getSelectedRow();
        System.out.println(linha);
        if(linha == -1) {
            JOptionPane.showMessageDialog(null, "Selecione um livro para editar.");
            return;
        }
        linhaEdicao = linha;
        CadastroLivros l = listaLivros.get(linha);
        txtTitulo.setText(l.titulo);
        txtAutor.setText(l.autor);
        txtAnoPublicacao.setText(l.anoPublicacao);
        
        if(l.tipo == 'F'){
            rdoFisico.setSelected(true);
        }
        else if(l.situacaoLeitura == 'N'){
            rdoNaoIniciado.setSelected(true);
        }
        else {
            cmbCategorias.setSelectedItem(l.categorias);
        }
    }//GEN-LAST:event_btnEditarActionPerformed

