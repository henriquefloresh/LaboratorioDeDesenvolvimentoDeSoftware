    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        if(rdoFisico.isSelected()){
            tipo = 'F';
            JOptionPane.showMessageDialog(null, "Tipo fisico selecionado", "Alerta", JOptionPane.OK_OPTION);
            
             
        }
        else if(rdoDigital.isSelected()){
            tipo = 'D';
            JOptionPane.showMessageDialog(null, "Tipo digital selecionado", "Alerta", JOptionPane.OK_OPTION);
            
             
        }
        else{
            JOptionPane.showMessageDialog(null, "Selecione um tipo de livro: ", "Erro", JOptionPane.ERROR_MESSAGE);
        }
        
        
        if(rdoNaoIniciado.isSelected()){
            tipo = 'N';
            JOptionPane.showMessageDialog(null, "Situação Leitura: não iniciada selecionada", "Alerta", JOptionPane.OK_OPTION);
            
             
        }
        else if(rdoEmAndamento.isSelected()){
            tipo = 'E';
            JOptionPane.showMessageDialog(null, "Situação Leitura: em andamento selecionado", "Alerta", JOptionPane.OK_OPTION);
            
             
        }
        else if(rdoConcluido.isSelected()){
            tipo = 'C';
            JOptionPane.showMessageDialog(null, "Situação Leitura: concluído selecionado", "Alerta", JOptionPane.OK_OPTION);
            
             
        }
        else{
            JOptionPane.showMessageDialog(null, "Selecione um tipo de livro: ", "Erro", JOptionPane.ERROR_MESSAGE);
        }
        
        String categorias = cmbCategorias.getSelectedItem()+"";
        
        CadastroLivros l = new CadastroLivros(txtTitulo.getText(), txtAutor.getText(), categorias, txtAnoPublicacao.getText(), tipo, situacaoLeitura);
        
        if(linhaEdicao == -1) {
            listaLivros.add(l);
        }
        else{
            listaLivros.set(linhaEdicao, l);
            linhaEdicao = -1;
        }
        arquivo.gravaArquivo();
        carregarTabela();
        JOptionPane.showMessageDialog(null, "Dados salvos com sucesso!");
        
        

        
        txtTitulo.setText("");
        txtAutor.setText("");
        txtAnoPublicacao.setText("");
        btnGrpTipo.clearSelection();
        btnGrpSituacaoLeitura.clearSelection();
        cmbCategorias.setSelectedIndex(0);
        
         
        
        System.out.println("Pessoa adicionada!");
        for (CadastroLivros livro : listaLivros) {
            System.out.println(livro);
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

